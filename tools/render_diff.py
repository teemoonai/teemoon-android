#!/usr/bin/env python3
"""Diff a screen's render record against the iOS record vendored for it.

    tools/render_diff.py                       # every screen with both halves
    tools/render_diff.py --gate                # exit 1 on a difference or a stale record
    tools/render_diff.py --screen trust.none

The contract is docs/RENDER_RECORD.md. Android's half is regenerated by
`./gradlew test` (RenderRecordTest writes to app/build/renderRecord/); iOS's is
vendored under parity/render/ios/ and carries the sha it was produced at.

STALENESS IS A FAILURE, NOT A WARNING, and it is the reason this file has a
freshness check at all. `ParityCaptureUITests.swift` — the last cross-repo
dependency of this exact shape — rotted into an untracked file frozen at the port
baseline while iOS moved 125 commits, and nothing in either repo could report it.
A record older than the code it claims to describe is worse than no record,
because it reads as agreement.

Only the iOS half is stored. Android's is produced live from the real primitives
on every run, so the two frozen-things-agreeing failure cannot happen here: only
one of them is ever frozen.
"""
import argparse, json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ANDROID_DIR = ROOT / "app" / "build" / "renderRecord"
IOS_DIR = ROOT / "parity" / "render" / "ios"

# Compared field by field so a report names WHAT differs, not just that something does.
FIELDS = ["glyph", "fontSize", "fontWeight", "color", "padding", "corner"]


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True).stdout.strip()


def key(row):
    """The join: kind + normalised text, or the glyph when there is no text.

    Never positional. A positional key silently pairs two elements that were
    never the same one, which is the failure the text join exists to remove —
    see the join section of docs/RENDER_RECORD.md.
    """
    return (row.get("kind", ""), row.get("text", ""), row.get("glyph") or "")


def screens():
    for ios_file in sorted(IOS_DIR.glob("*.json")) if IOS_DIR.exists() else []:
        yield ios_file.stem, ios_file, ANDROID_DIR / ios_file.name


def stale(ios_doc, screen, ios_repo):
    """True when the vendored record predates the code it claims to describe."""
    sha = ios_doc.get("producedAt")
    if not sha:
        return "no producedAt sha — a record that cannot be dated cannot be trusted"
    if not (ios_repo / ".git").exists():
        return None                      # cannot check without the checkout; not a failure
    m = json.loads((ROOT / "ports.json").read_text())
    for e in m["entries"]:
        for src in e.get("sources", []):
            if src.get("path", "").startswith("teemoon/Views/") and src.get("sha"):
                moved = git(ios_repo, "log", "--oneline", f"{sha}..{src['sha']}", "--", src["path"])
                if moved:
                    return (f"produced at {sha}, but {src['path']} is ported from {src['sha']} "
                            f"which is NEWER — the record predates the code it describes")
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ios", default="../teemoon-ios")
    ap.add_argument("--gate", action="store_true")
    ap.add_argument("--screen")
    args = ap.parse_args()
    ios_repo = (ROOT / args.ios).resolve()

    if not IOS_DIR.exists():
        print(f"(no vendored iOS records at {IOS_DIR.relative_to(ROOT)} — the iOS producer is not built yet)")
        print("  The Android half alone is Android compared against its own past, which certifies")
        print("  the port against itself. Reported, never gated. See docs/RENDER_RECORD.md.")
        return 0

    problems, compared = [], 0
    for name, ios_file, and_file in screens():
        if args.screen and name != args.screen:
            continue
        ios_doc = json.loads(ios_file.read_text())
        why = stale(ios_doc, name, ios_repo)
        if why:
            problems.append((name, f"STALE RECORD — {why}"))
            continue
        if not and_file.exists():
            problems.append((name, "no Android record — run ./gradlew test"))
            continue
        and_doc = json.loads(and_file.read_text())
        ios_rows = {key(r): r for r in ios_doc.get("rows", [])}
        and_rows = {key(r): r for r in and_doc.get("rows", [])}
        compared += 1
        for k in sorted(set(ios_rows) | set(and_rows)):
            i, a = ios_rows.get(k), and_rows.get(k)
            label = f"{k[0]} \"{k[1] or k[2]}\""
            if i is None:
                problems.append((name, f"{label}: on Android only")); continue
            if a is None:
                problems.append((name, f"{label}: on iOS only")); continue
            for f in FIELDS:
                if i.get(f) != a.get(f):
                    problems.append((name, f"{label}: {f} iOS={i.get(f)!r} Android={a.get(f)!r}"))

    print(f"render diff: {compared} screen(s) compared")
    last = None
    for name, msg in problems:
        if name != last:
            print(f"\n  {name}")
            last = name
        print(f"    {msg}")
    if not problems:
        print("  clean — every joined element reports the same resolved values")
    return 1 if (args.gate and problems) else 0


if __name__ == "__main__":
    sys.exit(main())
